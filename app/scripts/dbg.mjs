import { chromium } from '@playwright/test';
const b = await chromium.launch(); const c = await b.newContext(); const p = await c.newPage();
p.on('console', m => console.log('console', m.text()));
p.on('pageerror', e => console.log('err', e.message));
p.on('requestfailed', r => console.log('failed', r.url(), r.failure()?.errorText));
await p.goto('http://localhost:4173/');
await p.evaluate(() => navigator.serviceWorker.ready);
await p.reload();
console.log('controlled', await p.evaluate(() => !!navigator.serviceWorker.controller));
await c.setOffline(true);
await p.reload().catch(e => console.log('reload', e.message));
console.log((await p.content()).slice(0, 300));
await b.close();
